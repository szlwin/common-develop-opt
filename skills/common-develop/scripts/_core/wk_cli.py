"""Parser construction for the public ``wk`` command-line entry point."""
from __future__ import annotations

import argparse
from types import ModuleType


def _add_intake_args(parser: argparse.ArgumentParser) -> None:
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("-b", "--bug")
    group.add_argument("-f", "--feature")
    parser.add_argument("--classification", choices=["new-requirement", "requirement-change", "simple-optimization", "needs-confirmation"], default="")
    parser.add_argument("--related-requirement", default="")
    parser.add_argument("--related-feature", default="")
    parser.add_argument("--reason", default="")
    parser.add_argument("--evidence-ref", action="append", default=[])
    for flag, dest in (
        ("business-logic", "business_logic"), ("data-model", "data_model"),
        ("api-contract", "api_contract"), ("permission", "permission"),
        ("workflow", "workflow"), ("persistence", "persistence"),
        ("external-side-effect", "external_side_effect"), ("migration", "migration"),
        ("dependency", "dependency"),
    ):
        parser.add_argument(f"--{flag}-impact", dest=f"{dest}_impact", choices=["NONE", "CHANGED", "UNKNOWN"], default="UNKNOWN")


def build_parser(wk_module: ModuleType) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=wk_module.__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    start = commands.add_parser("start", help="classify and initialize one request transactionally")
    wk_module.agent_context.add_agent_argument(start)
    start.add_argument("--doc-root", required=True)
    start.add_argument("--version", required=True)
    _add_intake_args(start)
    start.add_argument("--changed-scope", action="append", default=[], help="governance change scope; repeatable")
    start.add_argument("--graph", default="", help="optional engineering graph JSON")
    start.add_argument("--changed-ref", action="append", default=[], help="changed graph ref; repeatable")
    start.add_argument("--constraints", default="", help="optional JSON project constraints payload")
    start.add_argument("--current-profile", default="", help="current governance profile for advisory override tracking")
    start.add_argument("--exploration", action="store_true", help="mark the request as exploratory work")
    start.add_argument("--override-reason", default="", help="reason for overriding a differing current governance profile")
    wk_module.work_mode.add_mode_arguments(start, include_sync=True)
    start.add_argument("--apply", action="store_true", help="create the classified task; default is preview")
    start.add_argument("--json", action="store_true", help="emit machine-readable result or error")
    start.set_defaults(func=wk_module.command_start)
    status = commands.add_parser("status", help="show one task status")
    wk_module.agent_context.add_agent_argument(status)
    status.add_argument("--task-dir", required=True)
    status_view = status.add_mutually_exclusive_group()
