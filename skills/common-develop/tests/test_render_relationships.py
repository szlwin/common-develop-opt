from __future__ import annotations

import copy
import tempfile
import unittest
from pathlib import Path

import render_relationships
import simple_yaml


ROOT = Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / "tests" / "fixtures" / "structured-docs" / "dependency_impact.yaml"


class RenderRelationshipsTest(unittest.TestCase):
    def document(self):
        return copy.deepcopy(simple_yaml.load(EXAMPLE))

    def test_example_renders_relationship_and_sequence_diagrams(self) -> None:
        result = render_relationships.render(self.document())
        self.assertIn("flowchart LR", result)
        self.assertIn("需求—需求关系图", result)
        self.assertIn("需求—功能追踪图", result)
        self.assertIn("功能—功能影响图", result)
        self.assertIn("sequenceDiagram", result)
        self.assertIn("REL-ORDER-CANCEL-REFUND", result)
        self.assertIn("CMI-ORDER-CREATE", result)
        self.assertIn("GENERATED by scripts/render_relationships.py", result)

    def test_unsupported_node_type_is_rejected(self) -> None:
        document = self.document()
        document["nodes"][0]["type"] = "UNKNOWN"
        with self.assertRaisesRegex(render_relationships.RelationshipError, "unsupported type"):
            render_relationships.render(document)

    def test_unknown_relationship_node_is_rejected(self) -> None:
        document = self.document()
        document["relationships"][0]["to"] = "UNKNOWN-F01"
        with self.assertRaisesRegex(render_relationships.RelationshipError, "unknown node"):
            render_relationships.render(document)

    def test_unknown_policy_target_is_rejected(self) -> None:
        document = self.document()
        document["impactPolicies"][0]["targetRefs"] = ["UNKNOWN-F01"]
        with self.assertRaisesRegex(render_relationships.RelationshipError, "unknown target"):
            render_relationships.render(document)

    def test_duplicate_step_order_is_rejected(self) -> None:
        document = self.document()
        document["crossModuleImplementations"][0]["steps"][1]["order"] = 1
        with self.assertRaisesRegex(render_relationships.RelationshipError, "duplicate step order"):
            render_relationships.render(document)

    def test_duplicate_semantic_relationship_is_rejected(self) -> None:
        document = self.document()
        duplicate = copy.deepcopy(document["relationships"][0])
        duplicate["id"] = "REL-DUPLICATE"
        document["relationships"].append(duplicate)
        with self.assertRaisesRegex(render_relationships.RelationshipError, "duplicate semantic relationship"):
            render_relationships.render(document)

    def test_dependency_cycle_is_rejected(self) -> None:
        document = self.document()
        first = document["relationships"][1]
        first["type"] = "DEPENDS_ON"
        reverse = copy.deepcopy(first)
        reverse["id"] = "REL-DEPENDENCY-CYCLE"
        reverse["from"], reverse["to"] = first["to"], first["from"]
        document["relationships"].append(reverse)
        with self.assertRaisesRegex(render_relationships.RelationshipError, "dependency relationship cycle"):
            render_relationships.render(document)

    def test_non_contiguous_step_order_is_rejected(self) -> None:
        document = self.document()
        document["crossModuleImplementations"][0]["steps"][-1]["order"] = 99
        with self.assertRaisesRegex(render_relationships.RelationshipError, "orders must be contiguous"):
            render_relationships.render(document)

    def test_empty_policy_targets_are_rejected(self) -> None:
        document = self.document()
        document["impactPolicies"][0]["targetRefs"] = []
        with self.assertRaisesRegex(render_relationships.RelationshipError, "targetRefs must be non-empty"):
            render_relationships.render(document)

    def test_cli_check_does_not_require_output(self) -> None:
        original = render_relationships.sys.argv
        try:
            render_relationships.sys.argv = [
                "render_relationships.py",
                "--input",
                str(EXAMPLE),
                "--check",
            ]
            self.assertEqual(0, render_relationships.main())
        finally:
            render_relationships.sys.argv = original

    def test_cli_writes_markdown(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "relations.md"
            original = render_relationships.sys.argv
            try:
                render_relationships.sys.argv = [
                    "render_relationships.py",
                    "--input",
                    str(EXAMPLE),
                    "--output",
                    str(output),
                ]
                self.assertEqual(0, render_relationships.main())
            finally:
                render_relationships.sys.argv = original
            self.assertTrue(output.is_file())
            self.assertIn("跨模块订购实现映射", output.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
